#!/usr/bin/env node
/**
 * Generates shared Trailhead Arcade design tokens and AR gameplay configuration
 * for both Web (loota) and iOS (loota-mobile, when present as a sibling repo).
 *
 * Source of truth:
 *   - shared/experience/design-tokens.json
 *   - shared/experience/ar-gameplay.json
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');

const designTokensPath = path.join(repoRoot, 'shared/experience/design-tokens.json');
const arGameplayPath = path.join(repoRoot, 'shared/experience/ar-gameplay.json');

const designTokens = JSON.parse(fs.readFileSync(designTokensPath, 'utf8'));
const arGameplay = JSON.parse(fs.readFileSync(arGameplayPath, 'utf8'));

function toKebab(str) {
  return str.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function hexToSwiftUInt(hex) {
  return `0x${hex.replace('#', '').toUpperCase()}`;
}

function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

// 1. Web CSS tokens
const cssLines = [
  '/* AUTO-GENERATED by scripts/sync-experience.mjs — DO NOT EDIT DIRECTLY */',
  '/* Edit shared/experience/design-tokens.json and run: npm run sync:experience */',
  '',
  ':root {',
  ...Object.entries(designTokens.colors).map(
    ([key, val]) => `  --loota-ar-${toKebab(key)}: ${val};`
  ),
  ...Object.entries(designTokens.radii).map(
    ([key, val]) => `  --loota-ar-radius-${toKebab(key)}: ${val}px;`
  ),
  `  --loota-ar-border-width: ${designTokens.borders.standardPx}px;`,
  `  --loota-ar-modal-border-width: ${designTokens.borders.modalPx}px;`,
  `  --loota-ar-shadow-cta: 0 ${designTokens.shadows.ctaOffsetPx}px 0 ${designTokens.colors.ink};`,
  `  --loota-ar-shadow-cta-pressed: 0 ${designTokens.shadows.ctaPressedOffsetPx}px 0 ${designTokens.colors.ink};`,
  `  --loota-ar-shadow-card: 0 ${designTokens.shadows.cardOffsetPx}px 0 rgba(22, 38, 29, 0.16);`,
  `  --loota-ar-shadow-modal: 0 ${designTokens.shadows.modalOffsetPx}px 0 ${designTokens.colors.ink};`,
  '}',
  '',
];

const webCssPath = path.join(repoRoot, 'src/styles/trailhead-ar-tokens.css');
ensureDir(webCssPath);
fs.writeFileSync(webCssPath, cssLines.join('\n'), 'utf8');

// 2. Web TypeScript config
const tsContent = `// AUTO-GENERATED by scripts/sync-experience.mjs — DO NOT EDIT DIRECTLY
// Edit shared/experience/{design-tokens,ar-gameplay}.json and run: npm run sync:experience

export const DESIGN_TOKENS = ${JSON.stringify(designTokens, null, 2)} as const;

export const AR_GAMEPLAY_CONFIG = ${JSON.stringify(arGameplay, null, 2)} as const;

export type DesignTokens = typeof DESIGN_TOKENS;
export type ARGameplayConfig = typeof AR_GAMEPLAY_CONFIG;
export type CoinStyle = 'classic' | 'thickRim' | 'detailed' | 'beveled';

export interface ExperienceConfigPayload {
  designTokens: DesignTokens;
  arGameplay: ARGameplayConfig;
}
`;

const webTsPath = path.join(repoRoot, 'src/lib/ar/experienceConfig.ts');
ensureDir(webTsPath);
fs.writeFileSync(webTsPath, tsContent, 'utf8');

console.log(`Generated Web tokens: ${path.relative(repoRoot, webCssPath)}`);
console.log(`Generated Web config: ${path.relative(repoRoot, webTsPath)}`);

// 3. Optional iOS Swift generation when sibling loota-mobile repo exists
const iosProjectDir = path.resolve(repoRoot, '../loota-mobile/loota/loota');
if (fs.existsSync(iosProjectDir)) {
  const iosGeneratedDir = path.join(iosProjectDir, 'Generated');

  const swiftTokens = `// AUTO-GENERATED by loota/scripts/sync-experience.mjs — DO NOT EDIT DIRECTLY
// Source: loota/shared/experience/design-tokens.json (${designTokens.themeName} v${designTokens.version})

import SwiftUI

enum TrailheadColor {
${Object.entries(designTokens.colors)
  .map(([key, val]) => `    static let ${key} = Color(trailheadHex: ${hexToSwiftUInt(val)})`)
  .join('\n')}
}

enum TrailheadMetrics {
${Object.entries(designTokens.radii)
  .map(([key, val]) => `    static let radius_${key}: CGFloat = ${val}`)
  .join('\n')}
    static let borderWidth: CGFloat = ${designTokens.borders.standardPx}
    static let modalBorderWidth: CGFloat = ${designTokens.borders.modalPx}
    static let ctaShadowOffset: CGFloat = ${designTokens.shadows.ctaOffsetPx}
    static let ctaPressedShadowOffset: CGFloat = ${designTokens.shadows.ctaPressedOffsetPx}
}

struct TrailheadTactileButtonStyle: ButtonStyle {
    var fillTop: Color = TrailheadColor.blazeBright
    var fillBottom: Color = TrailheadColor.blaze
    var foreground: Color = TrailheadColor.surface
    var shadowHeight: CGFloat = TrailheadMetrics.ctaShadowOffset
    var cornerRadius: CGFloat = TrailheadMetrics.radius_button

    func makeBody(configuration: Configuration) -> some View {
        let pressed = configuration.isPressed
        configuration.label
            .font(.system(size: 16, weight: .heavy, design: .rounded))
            .foregroundStyle(foreground)
            .padding(.horizontal, 18)
            .padding(.vertical, 13)
            .background(
                LinearGradient(colors: [fillTop, fillBottom], startPoint: .top, endPoint: .bottom)
            )
            .clipShape(RoundedRectangle(cornerRadius: cornerRadius, style: .continuous))
            .overlay(
                RoundedRectangle(cornerRadius: cornerRadius, style: .continuous)
                    .stroke(TrailheadColor.ink, lineWidth: TrailheadMetrics.borderWidth)
            )
            .background(
                RoundedRectangle(cornerRadius: cornerRadius, style: .continuous)
                    .fill(TrailheadColor.ink)
                    .offset(y: pressed ? TrailheadMetrics.ctaPressedShadowOffset : shadowHeight)
            )
            .offset(y: pressed ? shadowHeight - TrailheadMetrics.ctaPressedShadowOffset : 0)
            .animation(.spring(response: 0.18, dampingFraction: 0.65), value: pressed)
    }
}

extension Color {
    init(trailheadHex hex: UInt, alpha: Double = 1.0) {
        self.init(
            .sRGB,
            red: Double((hex >> 16) & 0xFF) / 255.0,
            green: Double((hex >> 8) & 0xFF) / 255.0,
            blue: Double(hex & 0xFF) / 255.0,
            opacity: alpha
        )
    }
}
`;

  const swiftARConfig = `// AUTO-GENERATED by loota/scripts/sync-experience.mjs — DO NOT EDIT DIRECTLY
// Source: loota/shared/experience/ar-gameplay.json (v${arGameplay.version})

import Foundation

enum LootaARConfig {
    static let coinStyle = "${arGameplay.coinStyle}"
    static let focusRangeMeters: Float = ${arGameplay.gameplay.focusRangeMeters}
    static let degradedGpsFocusRangeMeters: Float = ${arGameplay.gameplay.degradedGpsFocusRangeMeters}
    static let hotspotXMin: Double = ${arGameplay.gameplay.focusHotspot.xMin}
    static let hotspotXMax: Double = ${arGameplay.gameplay.focusHotspot.xMax}
    static let hotspotYMin: Double = ${arGameplay.gameplay.focusHotspot.yMin}
    static let hotspotYMax: Double = ${arGameplay.gameplay.focusHotspot.yMax}
    static let walkUpCollectMeters: Float = ${arGameplay.gameplay.walkUpCollectMeters}
    static let summonCollectMeters: Float = ${arGameplay.gameplay.summonCollectMeters}
    static let summonSpeedMinMps: Float = ${arGameplay.gameplay.summonSpeedMinMps}
    static let summonSpeedMaxMps: Float = ${arGameplay.gameplay.summonSpeedMaxMps}
    static let summonScaleMax: Float = ${arGameplay.gameplay.summonScaleMax}
    static let bobAmplitudeMeters: Float = ${arGameplay.gameplay.bobAmplitudeMeters}
    static let bobPeriodSec: Double = ${arGameplay.gameplay.bobPeriodSec}
    static let spinPeriodSec: Double = ${arGameplay.gameplay.spinPeriodSec}
    static let compassSmoothingFactor: Double = ${arGameplay.tracking.compassSmoothingFactor}
    static let completionPollIntervalSec: TimeInterval = ${arGameplay.gameplay.completionPollIntervalMs / 1000}
}
`;

  const swiftTokensPath = path.join(iosGeneratedDir, 'LootaDesignTokens.swift');
  const swiftARConfigPath = path.join(iosGeneratedDir, 'LootaARConfig.swift');
  ensureDir(swiftTokensPath);
  fs.writeFileSync(swiftTokensPath, swiftTokens, 'utf8');
  fs.writeFileSync(swiftARConfigPath, swiftARConfig, 'utf8');

  console.log(`Synced iOS tokens: ${swiftTokensPath}`);
  console.log(`Synced iOS AR config: ${swiftARConfigPath}`);
} else {
  console.log('Sibling loota-mobile repo not found; skipped iOS Swift generation.');
}
